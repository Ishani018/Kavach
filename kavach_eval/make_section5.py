"""
make_section5.py — one-command §5 (and §4 cost) table generation
=================================================================

Consumes Parv's minister_runs.jsonl and emits the LaTeX table files that
section_5_frontier.tex / section_4_deployment.tex \\input, replacing the
[TBD] slots with measured numbers. Ties together the pieces that already
exist (eval_harness: correlation/rho, ablation, latency; adaptive_attack v3:
the frontier) behind a single entry point so that when the real dump lands
the workflow is exactly:

    python kavach_eval/make_section5.py minister_runs.jsonl --rho-auto
    cd paper && pdflatex skeleton_aisec.tex

Until the real dump arrives, run it on a synthetic fixture to verify the
pipeline end to end (the emitted tables are watermarked SYNTHETIC and must
not be submitted):

    python kavach_eval/make_synthetic.py --n 600 --rho 0.35 --out /tmp/s.jsonl
    python kavach_eval/make_section5.py /tmp/s.jsonl --rho-auto --synthetic

Outputs (to paper/tables/):
    tab_frontier.tex     §5  veto / Bayesian / hybrid × clean-FPR + ASR@K
    tab_ablation.tex     §5  1..N ministers (+/- COMPASS, +/- trajectory)
    tab_correlation.tex  §5  inter-minister error correlation (the rho)
    tab_cost.tex         §4  latency percentiles + embeds/decision
    section5_macros.tex  \\newcommand snapshots (\\FrontierVetoFPR etc.) so the
                         PROSE [TBD]s can be replaced by \\-macros too
"""
from __future__ import annotations

import argparse
import os
import sys
import tempfile
from pathlib import Path

_HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(_HERE))
sys.path.insert(0, str(_HERE.parent))

import eval_harness as eh
import adaptive_attack as aa
from parliament import speaker_bayesian


# ── LaTeX helpers ────────────────────────────────────────────────────────────

def _watermark(synthetic: bool) -> str:
    return ("\n\\textcolor{red}{\\textbf{SYNTHETIC FIXTURE — NOT FOR SUBMISSION}}\\\\\n"
            if synthetic else "")


def _pct(x) -> str:
    return "--" if x is None else f"{100*x:.1f}\\%"


def _f(x, nd=3) -> str:
    return "--" if x is None else f"{x:.{nd}f}"


# ── §5 frontier table ────────────────────────────────────────────────────────

def frontier_table(runs, rho, veto, synthetic) -> tuple[str, dict]:
    n_min = max(len(r["minister_votes"]) for r in runs)
    variants = {
        "Pure veto (deployed)": aa.real_speaker,
        "Bayesian": aa.make_bayesian(rho),
        f"Hybrid (veto {veto:.2f})": aa.make_hybrid(rho, veto),
        "Max-score": aa.max_score,
        "Majority": aa.majority,
    }
    ks = list(range(0, min(n_min, 4) + 1))
    # gather
    rows = {}
    macros = {}
    for name, fn in variants.items():
        fpr = aa.fpr_clean(runs, fn)
        asr = {k: aa.asr_under_attack(runs, fn, k) for k in ks}
        rows[name] = (fpr, asr)
    # macros for the three headline variants
    macros["FrontierVetoFPR"] = _pct(rows["Pure veto (deployed)"][0])
    macros["FrontierBayesFPR"] = _pct(rows["Bayesian"][0])
    macros["FrontierHybridFPR"] = _pct(rows[f"Hybrid (veto {veto:.2f})"][0])
    if 2 in ks:
        macros["FrontierBayesASRKtwo"] = _pct(rows["Bayesian"][1][2])
        macros["FrontierHybridASRKtwo"] = _pct(rows[f"Hybrid (veto {veto:.2f})"][1][2])

    col = "l" + "c" * (1 + len(ks))
    head = " & ".join(["Aggregator", "Clean FPR"] + [f"ASR$_{{K={k}}}$" for k in ks])
    body = []
    for name, (fpr, asr) in rows.items():
        cells = [name, _pct(fpr)] + [_pct(asr[k]) for k in ks]
        body.append(" & ".join(cells) + " \\\\")
    tex = f"""% AUTO-GENERATED by make_section5.py — do not hand-edit.{_watermark(synthetic)}
\\begin{{table}}[t]
\\centering
\\caption{{Aggregation frontier: clean false-positive rate and attack-success
rate as an adaptive attacker corrupts $K$ ministers. Measured on
{len(runs)} replayed actions ($\\rho={rho:.3f}$).}}
\\label{{tab:frontier}}
\\small
\\begin{{tabular}}{{{col}}}
\\toprule
{head} \\\\
\\midrule
{chr(10).join(body)}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
"""
    return tex, macros


# ── §5 ablation table ────────────────────────────────────────────────────────

def ablation_table(runs, rho, synthetic) -> str:
    # Fresh reliability store in a unique temp dir per invocation: portable
    # (no hardcoded /tmp, which does not exist on Windows) and prevents a stale
    # Beta-Bernoulli posterior from leaking across runs and skewing the §5 table.
    with tempfile.TemporaryDirectory(prefix="kavach_s5_") as _td:
        sp = speaker_bayesian.BayesianSpeaker(
            store=speaker_bayesian.ReliabilityStore(
                os.path.join(_td, f"kavach_s5_{rho}.json")),
            rho=rho)
        abl = eh.ablation_n_ministers(runs, sp)
    body = []
    for label, m in abl.items():
        body.append(f"{label.replace('_', ' ')} & {_pct(m.asr)} & {_pct(m.fpr)} "
                    f"& {_f(m.accuracy)} \\\\")
    return f"""% AUTO-GENERATED by make_section5.py.{_watermark(synthetic)}
\\begin{{table*}}[t]
\\centering
\\caption{{Minister ablation (Bayesian aggregator, $\\rho={rho:.3f}$): does the
full parliament beat its strongest single minister?}}
\\label{{tab:ablation}}
\\small
\\begin{{tabular}}{{lccc}}
\\toprule
Configuration & ASR & FPR & Accuracy \\\\
\\midrule
{chr(10).join(body)}
\\bottomrule
\\end{{tabular}}
\\end{{table*}}
"""


# ── §5 correlation table ─────────────────────────────────────────────────────

def correlation_table(runs, synthetic) -> tuple[str, float]:
    ministers, matrix, avg_rho = eh.minister_correlation(runs)
    head = "Minister & " + " & ".join(ministers) + " \\\\"
    body = []
    for a in ministers:
        cells = [a]
        for b in ministers:
            v = matrix.get((a, b))
            cells.append("--" if v is None else f"{v:.2f}")
        body.append(" & ".join(cells) + " \\\\")
    tex = f"""% AUTO-GENERATED by make_section5.py.{_watermark(synthetic)}
\\begin{{table}}[t]
\\centering
\\caption{{Inter-minister error correlation. Average off-diagonal
$\\rho={avg_rho:.3f}$ is the correlation discount supplied to the Bayesian
aggregator.}}
\\label{{tab:correlation}}
\\small
\\begin{{tabular}}{{l{'c' * len(ministers)}}}
\\toprule
{head}
\\midrule
{chr(10).join(body)}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
"""
    return tex, avg_rho


# ── §4 cost table ────────────────────────────────────────────────────────────

def cost_table(runs, synthetic) -> str:
    lat = eh.latency_report(runs)
    body = []
    for name, d in lat.items():
        body.append(f"{name.replace('_', ' ')} & {_f(d['p50'], 0)} & "
                    f"{_f(d['p95'], 0)} & {_f(d['p99'], 0)} \\\\")
    note = ("" if any(d["p50"] for d in lat.values())
            else "\n% NOTE: dump has no latency_ms fields — table is empty; "
                 "ask Parv to include latency_ms per minister vote.")
    return f"""% AUTO-GENERATED by make_section5.py.{note}{_watermark(synthetic)}
\\begin{{table}}[t]
\\centering
\\caption{{Latency (ms) by minister and for the parallel parliament.}}
\\label{{tab:cost}}
\\small
\\begin{{tabular}}{{lccc}}
\\toprule
Component & p50 & p95 & p99 \\\\
\\midrule
{chr(10).join(body)}
\\bottomrule
\\end{{tabular}}
\\end{{table}}
"""


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    ap.add_argument("dump")
    ap.add_argument("--rho", type=float, default=0.05)
    ap.add_argument("--rho-auto", action="store_true",
                    help="measure rho from the dump instead of using --rho")
    ap.add_argument("--veto", type=float, default=0.90)
    ap.add_argument("--synthetic", action="store_true",
                    help="watermark outputs as a non-submittable fixture")
    ap.add_argument("--outdir", default=str(_HERE.parent / "paper" / "tables"))
    args = ap.parse_args()

    runs = aa.load(args.dump)
    Path(args.outdir).mkdir(parents=True, exist_ok=True)

    corr_tex, measured_rho = correlation_table(runs, args.synthetic)
    rho = measured_rho if args.rho_auto else args.rho

    front_tex, macros = frontier_table(runs, rho, args.veto, args.synthetic)
    abl_tex = ablation_table(runs, rho, args.synthetic)
    cost_tex = cost_table(runs, args.synthetic)

    out = Path(args.outdir)
    (out / "tab_frontier.tex").write_text(front_tex)
    (out / "tab_ablation.tex").write_text(abl_tex)
    (out / "tab_correlation.tex").write_text(corr_tex)
    (out / "tab_cost.tex").write_text(cost_tex)

    macro_lines = [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()]
    macro_lines.append(f"\\newcommand{{\\MeasuredRho}}{{{rho:.3f}}}")
    (out / "section5_macros.tex").write_text(
        "% AUTO-GENERATED macros — \\input in the preamble, use in prose.\n"
        + "\n".join(macro_lines) + "\n")

    print(f"Wrote 5 files to {out}/  (rho={rho:.3f}{' MEASURED' if args.rho_auto else ''})")
    for k, v in macros.items():
        print(f"  \\{k} = {v}")
    if args.synthetic:
        print("  ⚠ SYNTHETIC — tables watermarked, not for submission")


if __name__ == "__main__":
    main()
